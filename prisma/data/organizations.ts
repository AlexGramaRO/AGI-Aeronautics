export type SeedOrg = {
  name: string;
  kind: "ANSP" | "TRAINING_ACADEMY" | "UNIVERSITY" | "OTHER";
  country: string;
  city: string;
  lat: number;
  lng: number;
  website?: string;
  email?: string;
  contactTitle?: string;
  extraContacts?: { email: string; title: string }[];
  atmSystem?: string;
  simulatorKind?: "RADAR" | "TOWER" | "RADAR_AND_TOWER";
  simulatorVendor?: string;
  simulatorAcquired?: string;
  notes?: string;
};

const unpublished =
  "Named officers and contract price are omitted unless a public source states them.";

const coopans =
  "Shared COOPANS system supplied by Thales. The contracted upgrade is TopSky-ATC One, planned in three waves from 2028 to 2030.";

export function publishedContacts(org: SeedOrg): { email: string; title: string }[] {
  const rows: { email: string; title: string }[] = [];
  const push = (email?: string, title?: string) => {
    const clean = email?.trim().replace(/;+$/, "");
    if (!clean || rows.some((row) => row.email.toLowerCase() === clean.toLowerCase())) return;
    rows.push({ email: clean, title: title || "Public enquiry" });
  };
  push(org.email, org.contactTitle);
  for (const contact of org.extraContacts || []) push(contact.email, contact.title);
  return rows;
}

export function organizationSeedData(org: SeedOrg) {
  return {
    name: org.name,
    kind: org.kind,
    country: org.country,
    city: org.city,
    lat: org.lat,
    lng: org.lng,
    website: org.website ?? null,
    atmSystem: org.atmSystem ?? null,
    simulatorKind: (org.simulatorKind ?? "UNKNOWN") as SimulatorKind,
    simulatorVendor: org.simulatorVendor ?? null,
    simulatorAcquired: org.simulatorAcquired ?? null,
    notes: org.notes ?? null,
  };
}

